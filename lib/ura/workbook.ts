/**
 * Builds URA-shaped workbooks.
 *
 * URA publishes its returns as macro-enabled Excel templates (DT20002 for
 * income tax, DT2008 for PAYE). Those templates carry VBA that validates the
 * entry and, on VALIDATE, emits the compressed upload file the portal accepts.
 * We cannot run their VBA from a server, so instead we reproduce the template's
 * shape — same sheets, same schedules, same column order — pre-filled with the
 * taxpayer's figures and live SUM/cross-sheet formulas. The app runs the same
 * validation the macro would, then hands back the completed workbook, which the
 * user uploads to the URA portal exactly as they would the official template.
 *
 * Keeping the sheet and column layout aligned with the published forms is the
 * whole point: an officer reading the file sees the return they expect.
 */

import ExcelJS from 'exceljs'
import type { UraReturnBundle, ValidationReport } from './types'
import { round2 } from './uganda-tax'

const MONEY = '#,##0'
const HEADER_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1E3A5F' } }
const SUB_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFEDF2F7' } }
const TOTAL_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFDCE6F1' } }
const WHITE_BOLD: Partial<ExcelJS.Font> = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 }

function titleRow(ws: ExcelJS.Worksheet, text: string, span = 6): number {
  const row = ws.addRow([text])
  row.font = { bold: true, size: 13 }
  ws.mergeCells(row.number, 1, row.number, span)
  return row.number
}

function fieldRow(ws: ExcelJS.Worksheet, label: string, value: string | number, span = 6): number {
  const row = ws.addRow([label, value])
  row.getCell(1).font = { bold: true }
  if (typeof value === 'number') row.getCell(2).numFmt = MONEY
  ws.mergeCells(row.number, 2, row.number, span)
  return row.number
}

function headerRow(ws: ExcelJS.Worksheet, labels: string[]): number {
  const row = ws.addRow(labels)
  row.eachCell((cell) => {
    cell.fill = HEADER_FILL
    cell.font = WHITE_BOLD
    cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }
    cell.border = { bottom: { style: 'thin', color: { argb: 'FF9AA7B4' } } }
  })
  row.height = 22
  return row.number
}

function totalRow(ws: ExcelJS.Worksheet, label: string, labelSpan: number, value: number | { formula: string }): number {
  const row = ws.addRow([])
  const labelCell = row.getCell(1)
  labelCell.value = label
  labelCell.font = { bold: true }
  if (labelSpan > 1) ws.mergeCells(row.number, 1, row.number, labelSpan)
  const valueCell = row.getCell(labelSpan + 1)
  valueCell.value = value as any
  valueCell.numFmt = MONEY
  valueCell.font = { bold: true }
  for (let c = 1; c <= labelSpan + 1; c++) row.getCell(c).fill = TOTAL_FILL
  return row.number
}

function styleColumns(ws: ExcelJS.Worksheet, widths: number[]) {
  widths.forEach((w, i) => { ws.getColumn(i + 1).width = w })
}

function helpSheet(wb: ExcelJS.Workbook, returnType: 'income_tax' | 'paye', validation: ValidationReport | null) {
  const ws = wb.addWorksheet('Help')
  styleColumns(ws, [90])
  titleRow(ws, 'Jackisa Office — URA return workbook', 1)
  ws.addRow([])
  const lines = [
    'This workbook is generated by Jackisa Office in the layout of the official URA template.',
    returnType === 'income_tax'
      ? 'Form: DT20002 — Income Tax Return (Non-Individual).'
      : 'Form: DT2008 — PAYE Return.',
    '',
    'How to use it:',
    '1. Review the Return Details sheet and correct any taxpayer details.',
    '2. Check the schedule sheets — every line came from your invoices, expenses, notes and payroll.',
    '3. Read the Validation sheet. It runs the same checks the URA macro performs.',
    '4. When there are no errors, upload this file at ura.go.ug under e-Returns.',
    '',
    'The formulas are live: edit a line and the totals and tax computation update.',
  ]
  for (const l of lines) ws.addRow([l])
  ws.addRow([])
  ws.addRow([`Validation: ${validation ? (validation.ok ? 'PASSED' : `${validation.errors} error(s)`) : 'not run'}`]).font = { bold: true }
}

export async function buildWorkbook(bundle: UraReturnBundle, validation: ValidationReport | null): Promise<Buffer> {
  const wb = new ExcelJS.Workbook()
  wb.creator = 'Jackisa Office'
  wb.created = new Date()
  wb.properties.date1904 = false

  if (bundle.returnType === 'income_tax') buildIncomeTaxSheets(wb, bundle, validation)
  else buildPayeSheets(wb, bundle, validation)

  helpSheet(wb, bundle.returnType, validation)

  const buffer = await wb.xlsx.writeBuffer()
  return Buffer.from(buffer as ArrayBuffer)
}

// ---------------------------------------------------------------------------
// Income tax (DT20002)
// ---------------------------------------------------------------------------

function buildIncomeTaxSheets(wb: ExcelJS.Workbook, bundle: UraReturnBundle, validation: ValidationReport | null) {
  const data = bundle.incomeTax!
  const { taxpayer, period } = bundle

  // -- Return Details -------------------------------------------------------
  const rd = wb.addWorksheet('Return Details')
  styleColumns(rd, [34, 26, 18, 18, 18, 18])
  titleRow(rd, 'URA — Income Tax Return (Non-Individual)  •  DT20002')
  rd.addRow([])
  fieldRow(rd, 'Taxpayer name', taxpayer.name)
  fieldRow(rd, 'TIN', taxpayer.tin || '')
  fieldRow(rd, 'Email', taxpayer.email || '')
  fieldRow(rd, 'Phone', taxpayer.phone || '')
  fieldRow(rd, 'Period from', period.start)
  fieldRow(rd, 'Period to', period.end)
  fieldRow(rd, 'Return period', period.label)
  fieldRow(rd, 'Currency', bundle.currency)
  fieldRow(rd, 'Generated', bundle.generatedAt)
  rd.addRow([])
  const statusRow = rd.addRow(['Return status', 'draft'])
  statusRow.getCell(2).dataValidation = {
    type: 'list',
    allowBlank: false,
    formulae: ['"draft,submitted,filed"'],
  }
  const typeRow = rd.addRow(['Return type', 'Original'])
  typeRow.getCell(2).dataValidation = { type: 'list', allowBlank: false, formulae: ['"Original,Amended"'] }

  // -- Schedule A — Income --------------------------------------------------
  const inc = wb.addWorksheet('Schedule A - Income')
  styleColumns(inc, [14, 22, 30, 18, 18, 14])
  titleRow(inc, 'Schedule A — Business income')
  inc.addRow([])
  headerRow(inc, ['Date', 'Reference', 'Description', 'Amount (UGX)', 'VAT (UGX)', 'Status'])
  const incStart = inc.lastRow!.number + 1
  for (const line of [...data.invoices, ...data.sales, ...data.creditNotes]) {
    inc.addRow([line.date || '', line.reference || '', line.description || '', round2(line.amount || 0), round2((line as any).vat || 0), line.status || ''])
  }
  if (!data.invoices.length && !data.sales.length && !data.creditNotes.length) inc.addRow(['', '', 'No income lines in this period', 0, 0, ''])
  const incEnd = inc.lastRow!.number
  for (let r = incStart; r <= incEnd; r++) inc.getCell(r, 4).numFmt = MONEY
  const incTotalRow = totalRow(inc, 'Total business income', 3, { formula: `SUM(D${incStart}:D${incEnd})` })
  const incomeCell = `'Schedule A - Income'!D${incTotalRow}`

  // -- Schedule B — Expenses ------------------------------------------------
  const exp = wb.addWorksheet('Schedule B - Expenses')
  styleColumns(exp, [14, 22, 30, 18, 18, 14])
  titleRow(exp, 'Schedule B — Allowable deductions / expenses')
  exp.addRow([])
  headerRow(exp, ['Date', 'Reference', 'Description', 'Amount (UGX)', 'VAT (UGX)', 'Status'])
  const expStart = exp.lastRow!.number + 1
  for (const line of [...data.expenses, ...data.debitNotes]) {
    exp.addRow([line.date || '', line.reference || '', line.description || '', round2(line.amount || 0), 0, line.status || ''])
  }
  if (!data.expenses.length && !data.debitNotes.length) exp.addRow(['', '', 'No expense lines in this period', 0, 0, ''])
  const expEnd = exp.lastRow!.number
  for (let r = expStart; r <= expEnd; r++) exp.getCell(r, 4).numFmt = MONEY
  const expTotalRow = totalRow(exp, 'Total allowable expenses', 3, { formula: `SUM(D${expStart}:D${expEnd})` })
  const expenseCell = `'Schedule B - Expenses'!D${expTotalRow}`

  // -- Schedule C — Adjustments --------------------------------------------
  const adj = wb.addWorksheet('Schedule C - Adjustments')
  styleColumns(adj, [16, 30, 20, 18, 26])
  titleRow(adj, 'Schedule C — Adjustments, capital allowances and losses')
  adj.addRow([])
  headerRow(adj, ['Kind', 'Description', 'Reference', 'Amount (UGX)', 'Notes'])
  const adjStart = adj.lastRow!.number + 1
  const adjustmentRows = data.adjustments.filter((a) => a.kind === 'addition' || a.kind === 'deduction')
  for (const a of adjustmentRows) {
    adj.addRow([a.kind === 'addition' ? 'Add back' : 'Deduct', a.label, a.reference || '', round2(a.amount), a.notes || ''])
  }
  if (!adjustmentRows.length) adj.addRow(['', 'No adjustments added', '', 0, ''])
  const adjEnd = adj.lastRow!.number
  for (let r = adjStart; r <= adjEnd; r++) adj.getCell(r, 4).numFmt = MONEY
  const addRow = totalRow(adj, 'Total additions', 3, {
    formula: `SUMIF(A${adjStart}:A${adjEnd},"Add back",D${adjStart}:D${adjEnd})`,
  })
  const dedRow = totalRow(adj, 'Total deductions', 3, {
    formula: `SUMIF(A${adjStart}:A${adjEnd},"Deduct",D${adjStart}:D${adjEnd})`,
  })
  const additionsCell = `'Schedule C - Adjustments'!D${addRow}`
  const deductionsCell = `'Schedule C - Adjustments'!D${dedRow}`

  // -- Schedule D — Assets & Liabilities -----------------------------------
  const bal = wb.addWorksheet('Schedule D - Balances')
  styleColumns(bal, [16, 30, 20, 18, 26])
  titleRow(bal, 'Schedule D — Statement of assets and liabilities')
  bal.addRow([])
  headerRow(bal, ['Kind', 'Description', 'Reference', 'Amount (UGX)', 'Notes'])
  const balStart = bal.lastRow!.number + 1
  const balRows = data.adjustments.filter((a) => a.kind === 'asset' || a.kind === 'liability')
  for (const a of balRows) {
    bal.addRow([a.kind === 'asset' ? 'Asset' : 'Liability', a.label, a.reference || '', round2(a.amount), a.notes || ''])
  }
  if (!balRows.length) bal.addRow(['', 'No assets or liabilities added', '', 0, ''])
  const balEnd = bal.lastRow!.number
  for (let r = balStart; r <= balEnd; r++) bal.getCell(r, 4).numFmt = MONEY
  totalRow(bal, 'Total assets', 3, { formula: `SUMIF(A${balStart}:A${balEnd},"Asset",D${balStart}:D${balEnd})` })
  totalRow(bal, 'Total liabilities', 3, { formula: `SUMIF(A${balStart}:A${balEnd},"Liability",D${balStart}:D${balEnd})` })

  // -- Tax Computation ------------------------------------------------------
  const calc = wb.addWorksheet('Tax Computation')
  styleColumns(calc, [44, 22])
  titleRow(calc, 'Income tax computation', 2)
  calc.addRow([])
  const c = data.computation
  calc.addRow(['Gross business income', { formula: incomeCell } as any]).getCell(2).numFmt = MONEY
  calc.addRow(['Less: allowable expenses', { formula: expenseCell } as any]).getCell(2).numFmt = MONEY
  calc.addRow(['Add: adjustments', { formula: additionsCell } as any]).getCell(2).numFmt = MONEY
  calc.addRow(['Less: deductions', { formula: deductionsCell } as any]).getCell(2).numFmt = MONEY
  const chargeableRowNum = calc.lastRow!.number + 1
  const chargeableRow = calc.addRow(['Chargeable income', { formula: `B${chargeableRowNum - 4}-B${chargeableRowNum - 3}+B${chargeableRowNum - 2}-B${chargeableRowNum - 1}` } as any])
  chargeableRow.getCell(2).numFmt = MONEY
  chargeableRow.getCell(1).font = { bold: true }
  chargeableRow.getCell(2).font = { bold: true }
  const rateRow = calc.addRow([c.presumptive ? 'Tax rate (presumptive, ≤ 150m)' : 'Tax rate (standard)', c.rate])
  rateRow.getCell(2).numFmt = '0%'
  const taxRow = calc.addRow(['Tax payable (UGX)', { formula: `B${chargeableRowNum}*B${chargeableRowNum + 1}` } as any])
  taxRow.getCell(2).numFmt = MONEY
  taxRow.getCell(1).font = { bold: true }
  taxRow.getCell(2).font = { bold: true }
  taxRow.eachCell((cell) => { cell.fill = TOTAL_FILL })
  calc.addRow(['Note', c.presumptive
    ? 'Chargeable income is within the presumptive band — the 1% small-business rate applies.'
    : 'Chargeable income exceeds the presumptive threshold — the standard 30% rate applies.'])

  writeValidationSheet(wb, validation)
}

